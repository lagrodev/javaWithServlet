package ru.hexaend.util;

/**
 * Константы бизнес-ограничений для сущности «Контакт».
 *
 * <p>Содержит лимиты, применяемые при валидации контактных данных: максимальное количество
 * телефонных номеров у одного контакта и минимальное количество цифр в номере телефона.
 *
 * @author Vasily Melnik
 */
public final class ContactConstraints {

    /**
     * Максимальное количество телефонных номеров, привязанных к одному контакту.
     */
    public static final int MAX_PHONES = 3;

    /**
     * Минимальное количество цифр, которое должен содержать валидный номер телефона.
     */
    public static final int MIN_NUMBERS_IN_PHONE = 7;

    private ContactConstraints() {
        // Утилитарный класс — создание экземпляров запрещено
    }
}
