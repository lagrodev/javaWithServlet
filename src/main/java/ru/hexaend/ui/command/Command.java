package ru.hexaend.ui.command;

/**
 * Команда консольного интерфейса.
 *
 * <p>Каждая реализация инкапсулирует одно действие пользователя
 * (добавление, удаление, поиск и т.д.).</p>
 *
 * @author Vasily Melnik
 */
public interface Command {

    /**
     * Выполняет команду: взаимодействует с пользователем и вызывает сервис.
     */
    void execute();
}
